import {NextResponse} from "next/server";
import {db} from "@/lib/db";
import {apiUser,unauthorized,bad,failure,jsonBody,asString} from "@/lib/api";
export async function GET(){
 const user=await apiUser();if(!user)return unauthorized();
 try{const tasks=await db.studyTask.findMany({where:{userId:user.id},orderBy:{dueAt:"asc"},take:120});
  return NextResponse.json({tasks},{headers:{"Cache-Control":"no-store"}});}catch(e){return failure(e)}
}
export async function POST(request:Request){
 const user=await apiUser();if(!user)return unauthorized();
 const b=await jsonBody(request),action=asString(b?.action,25);
 try{
  if(action==="generate"){
   const eventId=asString(b?.eventId,100);
   const event=await db.examScheduleEvent.findFirst({where:{id:eventId,officialVerified:true,startsAt:{gt:new Date()}}});
   if(!event||!event.startsAt)return bad("Select a verified future exam to generate a schedule");
   const units=await db.syllabusUnit.findMany({where:{courseId:event.courseId||undefined},orderBy:{number:"asc"},take:12});
   if(!units.length)return bad("No syllabus units found for this event");
   const remaining=Math.floor((event.startsAt.getTime()-Date.now())/86400000),days=Math.max(1,Math.min(remaining,30)),tasks=[];
   for(let d=0;d<days;d++){
    const dueAt=new Date(Date.now()+d*86400000),unit=units[d%units.length];
    tasks.push({userId:user.id,title:"Revise "+unit.title+" · Unit "+unit.number,courseCode:asString(b?.courseCode,40)||null,
     dueAt,minutes:35,autoGenerated:true});
   }
   await db.studyTask.createMany({data:tasks});
   return NextResponse.json({ok:true,created:tasks.length});
  }
  if(action==="complete"){
   const id=asString(b?.id,100);await db.studyTask.updateMany({where:{id,userId:user.id},data:{completed:b?.completed===true}});
   return NextResponse.json({ok:true});
  }
  if(action==="create"){
   const title=asString(b?.title,180),dueAt=new Date(String(b?.dueAt||""));
   if(!title||!Number.isFinite(dueAt.getTime()))return bad("Valid task and due date required");
   const task=await db.studyTask.create({data:{userId:user.id,title,dueAt,minutes:Math.min(240,Math.max(5,Number(b?.minutes)||30))}});
   return NextResponse.json({task},{status:201});
  }
  return bad("Unknown planner action");
 }catch(e){return failure(e)}
}
